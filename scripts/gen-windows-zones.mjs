/**
 * Regenerate src/windows-zones.ts (IANA -> Windows time-zone id) from the
 * Unicode CLDR `windowsZones.xml` file.
 *
 *   node scripts/gen-windows-zones.mjs                 # downloads from GitHub
 *   node scripts/gen-windows-zones.mjs ./windowsZones.xml   # use a local copy
 *
 * Only the CLDR data is fetched; no mailbox or session is touched.
 */

import { readFile, writeFile } from "node:fs/promises";

const SOURCE_URL =
  "https://raw.githubusercontent.com/unicode-org/cldr/main/common/supplemental/windowsZones.xml";
const OUT = new URL("../src/windows-zones.ts", import.meta.url);

const arg = process.argv[2];
const xml = arg ? await readFile(arg, "utf8") : await (await fetch(SOURCE_URL)).text();

const version = /typeVersion="([^"]+)"/.exec(xml)?.[1] ?? "unknown";
const map = new Map();
for (const m of xml.matchAll(/<mapZone other="([^"]+)" territory="([^"]+)" type="([^"]+)"/g)) {
  const [, windows, , types] = m;
  for (const iana of types.split(/\s+/)) {
    if (!iana) continue;
    // A zone can appear under several Windows ids (e.g. Etc/GMT+12 in the
    // territory-specific rows); keep the first, which is the 001 default row.
    if (!map.has(iana)) map.set(iana, windows);
  }
}

// IANA ids renamed after the CLDR snapshot above was published; an alias gets
// the same Windows id as its older name.
const ALIASES = {
  "Europe/Kyiv": "Europe/Kiev",
  "America/Ciudad_Juarez": "America/Denver",
  "Asia/Kolkata": "Asia/Calcutta",
  "Asia/Yangon": "Asia/Rangoon",
  "Asia/Ho_Chi_Minh": "Asia/Saigon",
  "Atlantic/Faroe": "Atlantic/Faeroe",
  "America/Nuuk": "America/Godthab",
};
for (const [alias, old] of Object.entries(ALIASES)) {
  if (!map.has(alias) && map.has(old)) map.set(alias, map.get(old));
}

const lines = [...map.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([iana, win]) => `  ${JSON.stringify(iana)}: ${JSON.stringify(win)},`);

const out = `/**
 * IANA time-zone id -> Windows time-zone id.
 *
 * GENERATED by scripts/gen-windows-zones.mjs from the Unicode CLDR
 * windowsZones.xml (typeVersion ${version}). Do not edit by hand.
 */
export const IANA_TO_WINDOWS: Record<string, string> = {
${lines.join("\n")}
};
`;
await writeFile(OUT, out, "utf8");
console.log(`Wrote ${map.size} zones (CLDR ${version}) to src/windows-zones.ts`);
